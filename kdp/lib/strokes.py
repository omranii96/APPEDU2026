ADVANCE_GAP = 0.42  # space between letters, in units
SPACE_WIDTH = 0.9


def glyph(ch):
    if ch in GLYPHS:
        return GLYPHS[ch]
    if ch in ACCENTS:
        base, extra = ACCENTS[ch]
        return GLYPHS[base] + extra
    raise KeyError(f"No stroke glyph for {ch!r}")


def bbox(strokes):
    xs = [p[0] for s in strokes for p in s]
    ys = [p[1] for s in strokes for p in s]
    return min(xs), min(ys), max(xs), max(ys)


def glyph_width(ch):
    if ch == " ":
        return SPACE_WIDTH
    x0, _, x1, _ = bbox(glyph(ch))
    return max(x1 - x0, 0.2)


def text_width(text, gap=ADVANCE_GAP):
    if not text:
        return 0.0
    return sum(glyph_width(c) for c in text) + gap * (len(text) - 1)


def layout(text, gap=ADVANCE_GAP):
    """Yield (char, x_offset_units, strokes_normalised) for each glyph."""
    x = 0.0
    out = []
    for c in text:
        if c == " ":
            x += SPACE_WIDTH + gap
            continue
        g = glyph(c)
        x0 = bbox(g)[0]
        norm = [[(px - x0, py) for (px, py) in s] for s in g]
        out.append((c, x, norm))
        x += glyph_width(c) + gap
    return out
