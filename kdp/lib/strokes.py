"""
Pedagogical single-stroke alphabet (ball-and-stick / manuscript style).

Coordinate system, in "units":
    baseline  y = 0
    midline   y = 1   (x-height)
    top line  y = 2   (cap height / ascender)
    descender y = -1

Every glyph is an ORDERED list of strokes and every stroke is an ORDERED polyline,
so the stroke order and direction taught to the child are encoded in the data.
That is what lets us print numbered start dots and direction arrows - a feature
most KDP tracing books (which use a dotted font) cannot offer.
"""
import math

STEP_DEG = 6


def L(*pts):
    """Polyline through points."""
    return [tuple(map(float, p)) for p in pts]


def A(cx, cy, rx, ry, a0, a1, step=STEP_DEG):
    """Elliptical arc from angle a0 to a1 (degrees, a1 < a0 means clockwise)."""
    n = max(2, int(abs(a1 - a0) / step) + 1)
    out = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        out.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return out


def J(*parts):
    """Join several point lists into one continuous stroke."""
    out = []
    for p in parts:
        for q in p:
            if not out or (abs(out[-1][0] - q[0]) > 1e-6 or abs(out[-1][1] - q[1]) > 1e-6):
                out.append(q)
    return out


def DOT(x, y):
    """A dot (for i / j) is a stroke of a single point."""
    return [(float(x), float(y))]


def _fig8():
    pts = []
    for i in range(121):
        t = 2 * math.pi * i / 120
        pts.append((0.62 - 0.52 * math.sin(2 * t) * (1.0 if t < math.pi else 1.1) / 1.0, 1 + math.cos(t)))
    return pts


def _S(h=2.0):
    k = h / 2.0
    top = A(0.72, 1.5 * k, 0.62, 0.5 * k, 35, 270)
    bot = A(0.72, 0.5 * k, 0.72, 0.5 * k, 90, -145)
    return [J(top, bot)]


